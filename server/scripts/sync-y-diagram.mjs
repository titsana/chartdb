// Copies the client's src/lib/collab/y-diagram.ts into the server package.
//
// Why a copy and not an import: Node resolves `yjs` relative to the
// importing file, so a file under ../src would load the ROOT
// node_modules/yjs while Hocuspocus uses server/node_modules/yjs — two Yjs
// instances, and Y types from one aren't recognised by docs from the other.
// The server's Docker build stage also only sees server/.
//
// Runs automatically from .husky/pre-commit (and stages the result), so
// editing the client file is all you do. Manual run, if ever needed:
//   node server/scripts/sync-y-diagram.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const CLIENT = fileURLToPath(
    new URL('../../src/lib/collab/y-diagram.ts', import.meta.url)
);
const SERVER = fileURLToPath(
    new URL('../src/collab/y-diagram.ts', import.meta.url)
);

const HEADER = `// GENERATED by server/scripts/sync-y-diagram.mjs from
// src/lib/collab/y-diagram.ts — do not edit here, edit the client file and
// commit (the pre-commit hook regenerates this).
`;

export function toServerCopy(clientSource) {
    const domainImport =
        /^import type \{ (\w+) \} from '@\/lib\/domain\/[\w-]+';\n/gm;
    const names = [...clientSource.matchAll(domainImport)].map((m) => m[1]);
    if (names.length === 0) throw new Error('no domain imports found');
    let first = true;
    const body = clientSource.replace(domainImport, () => {
        if (!first) return '';
        first = false;
        return `import type {\n${names.map((n) => `    ${n},\n`).join('')}} from './y-diagram.types';\n`;
    });
    return HEADER + body;
}

export function readClient() {
    return readFileSync(CLIENT, 'utf8');
}

export function readServer() {
    return readFileSync(SERVER, 'utf8');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    writeFileSync(SERVER, toServerCopy(readClient()));
}
